class ThemeManager:
    """Small, dependency-free theme registry used by the Tk UI."""

    def __init__(self, name: str = "Dark"):
        self.name = name if name in THEMES else "Dark"

    @property
    def palette(self) -> dict:
        return deepcopy(THEMES[self.name])

    def select(self, name: str) -> dict:
        if name in THEMES:
            self.name = name
        return self.palette
